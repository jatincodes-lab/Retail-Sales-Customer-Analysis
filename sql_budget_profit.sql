CREATE OR REPLACE VIEW vw_budget_balance AS
SELECT COALESCE(SUM(amount),0) AS balance FROM store_budget;

CREATE OR REPLACE VIEW vw_profit_summary AS
SELECT COALESCE(SUM(si.quantity*si.unit_price),0) AS total_revenue,
       COALESCE(SUM(si.quantity*p.cost_price),0) AS total_cost,
       COALESCE(SUM(si.quantity*(si.unit_price-p.cost_price)),0) AS gross_profit
FROM sale_item si JOIN product p ON p.product_id=si.product_id;

CREATE OR REPLACE VIEW vw_supplier_purchases AS
SELECT sp.purchase_id,sp.supplier_id,s.supplier_name,sp.product_id,p.product_name,c.category_name,
       sp.quantity,sp.unit_cost,sp.total_cost,sp.purchased_by,sp.purchase_date,sp.notes
FROM supplier_purchase sp JOIN supplier s ON sp.supplier_id=s.supplier_id
JOIN product p ON sp.product_id=p.product_id JOIN category c ON p.category_id=c.category_id;

CREATE OR REPLACE VIEW vw_employee_duties AS
SELECT e.employee_id,e.first_name || ' ' || e.last_name AS employee_name,e.role,
       e.status AS employee_status,e.base_salary,d.duty_name,d.department,da.shift,da.assigned_date,
       da.status AS duty_status,m.first_name || ' ' || m.last_name AS assigned_by_name,da.notes
FROM employee e LEFT JOIN duty_assignment da ON e.employee_id=da.employee_id AND da.status='active'
LEFT JOIN duty d ON da.duty_id=d.duty_id LEFT JOIN employee m ON da.assigned_by=m.employee_id;

CREATE OR REPLACE VIEW vw_salary_summary AS
SELECT e.employee_id,e.first_name || ' ' || e.last_name AS employee_name,e.role,e.base_salary,
       COUNT(sp.payment_id) AS total_payments,COALESCE(SUM(sp.amount),0) AS total_paid,
       MAX(sp.payment_date) AS last_payment_date,MAX(sp.month_year) AS last_month_paid
FROM employee e LEFT JOIN salary_payment sp ON e.employee_id=sp.employee_id
GROUP BY e.employee_id,e.first_name,e.last_name,e.role,e.base_salary;

CREATE OR REPLACE FUNCTION touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at := CURRENT_TIMESTAMP; RETURN NEW; END;
$$;
CREATE TRIGGER store_settings_touch_updated_at BEFORE UPDATE ON store_settings
FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

CREATE OR REPLACE FUNCTION sp_assign_duty(p_employee_id integer,p_duty_id integer,p_assigned_by integer,
                                           p_shift varchar,p_notes text) RETURNS void
LANGUAGE plpgsql AS $$
BEGIN
  UPDATE duty_assignment SET status='cancelled'
   WHERE employee_id=p_employee_id AND status='active';
  INSERT INTO duty_assignment(employee_id,duty_id,assigned_by,shift,status,notes)
   VALUES(p_employee_id,p_duty_id,p_assigned_by,COALESCE(p_shift,'morning'),'active',p_notes);
END;
$$;

CREATE OR REPLACE FUNCTION sp_pay_salary(p_employee_id integer,p_amount numeric,p_month_year varchar,
                                          p_paid_by varchar,p_payment_method varchar,p_notes text) RETURNS void
LANGUAGE plpgsql AS $$
BEGIN
  IF p_amount IS NULL OR p_amount=0 THEN RAISE EXCEPTION 'Salary amount must be non-zero'; END IF;
  INSERT INTO salary_payment(employee_id,amount,month_year,paid_by,payment_method,notes)
   VALUES(p_employee_id,p_amount,p_month_year,p_paid_by,COALESCE(p_payment_method,'cash'),p_notes);
END;
$$;

COMMIT;
