BEGIN;

ALTER TABLE product ADD COLUMN cost_price numeric(10,2) NOT NULL DEFAULT 0 CHECK (cost_price >= 0);
ALTER TABLE product ADD COLUMN discount_all numeric(5,2) NOT NULL DEFAULT 0 CHECK (discount_all BETWEEN 0 AND 100);
ALTER TABLE product ADD COLUMN discount_registered numeric(5,2) NOT NULL DEFAULT 0 CHECK (discount_registered BETWEEN 0 AND 100);
UPDATE product SET cost_price = ROUND(unit_price * 0.60, 2);

CREATE TABLE store_budget (
    budget_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount numeric(12,2) NOT NULL,
    type varchar(20) NOT NULL DEFAULT 'deposit' CHECK (type IN ('deposit','purchase','adjustment')),
    description varchar(255), reference_id integer,
    created_by varchar(80) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE supplier_purchase (
    purchase_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id integer NOT NULL REFERENCES supplier(supplier_id) ON DELETE RESTRICT,
    product_id integer NOT NULL REFERENCES product(product_id) ON DELETE RESTRICT,
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_cost numeric(10,2) NOT NULL CHECK (unit_cost >= 0),
    total_cost numeric(10,2) NOT NULL CHECK (total_cost >= 0),
    purchased_by varchar(80) NOT NULL,
    purchase_date timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes text
);

CREATE TABLE store_settings (
    setting_key varchar(80) PRIMARY KEY,
    setting_value varchar(255) NOT NULL,
    updated_by varchar(80),
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE employee (
    employee_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(80) NOT NULL, last_name varchar(80) NOT NULL,
    email varchar(100) UNIQUE, phone varchar(20),
    role varchar(20) NOT NULL CHECK (role IN ('manager','cashier','stock_handler','rack_manager')),
    base_salary numeric(10,2) NOT NULL DEFAULT 0 CHECK (base_salary >= 0),
    join_date date NOT NULL DEFAULT CURRENT_DATE,
    status varchar(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
    address text
);

CREATE TABLE duty (
    duty_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    duty_name varchar(100) NOT NULL UNIQUE, description text,
    department varchar(80) NOT NULL DEFAULT 'General'
);

CREATE TABLE duty_assignment (
    assignment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id integer NOT NULL REFERENCES employee(employee_id) ON DELETE CASCADE,
    duty_id integer NOT NULL REFERENCES duty(duty_id) ON DELETE RESTRICT,
    assigned_by integer NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    assigned_date date NOT NULL DEFAULT CURRENT_DATE,
    shift varchar(20) NOT NULL DEFAULT 'morning' CHECK (shift IN ('morning','evening','night')),
    status varchar(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','completed','cancelled')),
    notes text
);

CREATE TABLE salary_payment (
    payment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id integer NOT NULL REFERENCES employee(employee_id) ON DELETE CASCADE,
    amount numeric(10,2) NOT NULL,
    payment_date date NOT NULL DEFAULT CURRENT_DATE,
    month_year varchar(20) NOT NULL,
    paid_by varchar(80) NOT NULL,
    payment_method varchar(20) NOT NULL DEFAULT 'cash' CHECK (payment_method IN ('cash','bank_transfer','cheque')),
    notes text
);

-- Protect the one-positive-payment-per-employee/month rule under concurrent requests.
CREATE UNIQUE INDEX salary_payment_one_payroll_per_month
    ON salary_payment(employee_id, month_year) WHERE amount > 0;

