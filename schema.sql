BEGIN;

CREATE TABLE category (
    category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name varchar(100) NOT NULL UNIQUE,
    description text
);

CREATE TABLE supplier (
    supplier_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name varchar(150) NOT NULL,
    contact_person varchar(100),
    phone varchar(20),
    email varchar(100) UNIQUE,
    address text
);

CREATE TABLE product (
    product_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id integer NOT NULL REFERENCES category(category_id) ON DELETE RESTRICT,
    supplier_id integer NOT NULL REFERENCES supplier(supplier_id) ON DELETE RESTRICT,
    product_name varchar(150) NOT NULL,
    description text,
    unit_price numeric(10,2) NOT NULL CHECK (unit_price > 0),
    reorder_level integer NOT NULL DEFAULT 10 CHECK (reorder_level >= 0)
);

CREATE TABLE inventory (
    inventory_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL UNIQUE REFERENCES product(product_id) ON DELETE CASCADE,
    quantity_in_stock integer NOT NULL DEFAULT 0 CHECK (quantity_in_stock >= 0),
    last_updated timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE customer (
    customer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(80) NOT NULL,
    last_name varchar(80) NOT NULL,
    email varchar(100) UNIQUE,
    phone varchar(20),
    address text,
    registration_date date NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE app_user (
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(80) NOT NULL UNIQUE,
    password_hash varchar(60) NOT NULL,
    role varchar(20) NOT NULL CHECK (role IN ('admin','manager','cashier')),
    active boolean NOT NULL DEFAULT true,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE sale (
    sale_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer REFERENCES customer(customer_id) ON DELETE SET NULL,
    sale_date timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total_amount numeric(10,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0)
);

CREATE TABLE sale_item (
    sale_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id integer NOT NULL REFERENCES sale(sale_id) ON DELETE CASCADE,
    product_id integer NOT NULL REFERENCES product(product_id) ON DELETE RESTRICT,
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(10,2) NOT NULL CHECK (unit_price > 0)
);

