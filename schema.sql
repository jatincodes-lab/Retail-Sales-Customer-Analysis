CREATE OR REPLACE VIEW vw_sales_summary AS
SELECT s.sale_id, s.sale_date, COALESCE(c.first_name || ' ' || c.last_name,'Guest') AS customer_name,
       COUNT(si.sale_item_id) AS total_items, s.total_amount
FROM sale s LEFT JOIN customer c ON s.customer_id=c.customer_id
JOIN sale_item si ON s.sale_id=si.sale_id
GROUP BY s.sale_id,s.sale_date,c.first_name,c.last_name,s.total_amount;

CREATE OR REPLACE VIEW vw_low_stock AS
SELECT p.product_id,p.product_name,i.quantity_in_stock,p.reorder_level,s.supplier_name,s.phone AS supplier_phone
FROM product p JOIN inventory i ON p.product_id=i.product_id JOIN supplier s ON p.supplier_id=s.supplier_id
WHERE i.quantity_in_stock <= p.reorder_level;

CREATE OR REPLACE VIEW vw_product_details AS
SELECT p.product_id,p.product_name,p.unit_price,c.category_name,s.supplier_name,i.quantity_in_stock
FROM product p JOIN category c ON p.category_id=c.category_id
JOIN supplier s ON p.supplier_id=s.supplier_id JOIN inventory i ON p.product_id=i.product_id;

CREATE OR REPLACE VIEW vw_customer_spend AS
SELECT c.customer_id,c.first_name || ' ' || c.last_name AS customer_name,c.email,
       COUNT(s.sale_id) AS total_orders,SUM(s.total_amount) AS total_spent,MAX(s.sale_date) AS last_purchase
FROM customer c JOIN sale s ON c.customer_id=s.customer_id
GROUP BY c.customer_id,c.first_name,c.last_name,c.email;

CREATE OR REPLACE VIEW vw_daily_sales AS
SELECT sale_date::date AS sale_day,COUNT(*) AS total_sales,SUM(total_amount) AS total_revenue
FROM sale GROUP BY sale_date::date;

CREATE OR REPLACE FUNCTION touch_last_updated() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.last_updated := CURRENT_TIMESTAMP; RETURN NEW; END;
$$;
CREATE TRIGGER inventory_touch_last_updated BEFORE UPDATE ON inventory
FOR EACH ROW EXECUTE FUNCTION touch_last_updated();

CREATE OR REPLACE FUNCTION sp_process_sale(p_customer_id integer DEFAULT NULL) RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE v_sale_id integer;
BEGIN
  INSERT INTO sale (customer_id) VALUES (p_customer_id) RETURNING sale_id INTO v_sale_id;
  RETURN v_sale_id;
END;
$$;

CREATE OR REPLACE FUNCTION sp_add_sale_item(p_sale_id integer,p_product_id integer,p_quantity integer) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE v_price numeric(10,2);
BEGIN
  IF p_quantity IS NULL OR p_quantity <= 0 THEN RAISE EXCEPTION 'Quantity must be positive'; END IF;
  SELECT unit_price INTO v_price FROM product WHERE product_id=p_product_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Product % not found',p_product_id; END IF;
  UPDATE inventory SET quantity_in_stock=quantity_in_stock-p_quantity
   WHERE product_id=p_product_id AND quantity_in_stock>=p_quantity;
  IF NOT FOUND THEN RAISE EXCEPTION 'Insufficient stock for product %',p_product_id; END IF;
  INSERT INTO sale_item(sale_id,product_id,quantity,unit_price) VALUES(p_sale_id,p_product_id,p_quantity,v_price);
  UPDATE sale SET total_amount=(SELECT COALESCE(SUM(quantity*unit_price),0) FROM sale_item WHERE sale_id=p_sale_id)
   WHERE sale_id=p_sale_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Sale % not found',p_sale_id; END IF;
END;
$$;

CREATE OR REPLACE FUNCTION sp_restock_product(p_product_id integer,p_quantity integer) RETURNS void
LANGUAGE plpgsql AS $$
BEGIN
  IF p_quantity IS NULL OR p_quantity <= 0 THEN RAISE EXCEPTION 'Quantity must be positive'; END IF;
  UPDATE inventory SET quantity_in_stock=quantity_in_stock+p_quantity WHERE product_id=p_product_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Product % not found',p_product_id; END IF;
END;
$$;

